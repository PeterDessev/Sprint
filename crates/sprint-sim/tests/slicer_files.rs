/// Lines a host would send (comments and blank lines removed).
fn commands(text: &str) -> Vec<String> {
    text.lines()
        .map(|l| l.split(';').next().unwrap_or("").trim().to_string())
        .filter(|l| !l.is_empty())
        .collect()
}

#[test]
fn prusaslicer_file_streams_cleanly() {
    let mut h = Host::booted(SimConfig {
        instant_moves: true,
        ..fast(1000.0)
    });
    // OctoPrint-style handshake.
    assert_eq!(h.command("N0 M110 N0*125"), vec!["ok"]);
    let cmds = commands(PRUSA_STYLE);
    h.control().clear_received();
    h.next_line = 1;
    let (resends, timeouts) = h.stream(&cmds, Duration::from_secs(5));
    assert_eq!((resends, timeouts), (0, 0));
    assert_eq!(h.control().received_commands(), cmds);
    // Marlin 2.1 without CANCEL_OBJECTS does not know M486; everything
    // else in the file is understood.
    let unknown: Vec<&String> = h
        .log
        .iter()
        .filter(|l| l.starts_with("echo:Unknown command"))
        .collect();
    assert_eq!(unknown, vec!["echo:Unknown command: \"M486 S0\""]);
    assert!(
        !h.log.iter().any(|l| l.starts_with("Error:")),
        "{:?}",
        h.log
    );
    let pos = h.command("M114");
    assert!(pos[0].starts_with("X:0.00 Y:200.00 Z:30.20"), "{pos:?}");
    let snap = h.control().snapshot();
    assert_eq!(snap.hotend_targets, vec![0.0]);
    assert_eq!(snap.bed_target, 0.0);
    assert_eq!(snap.fan, 0);
}


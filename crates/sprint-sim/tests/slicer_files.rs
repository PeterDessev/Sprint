#[test]
fn cura_file_streams_cleanly() {
    let mut h = Host::booted(SimConfig {
        instant_moves: true,
        ..fast(1000.0)
    });
    h.command("M110 N0");
    let cmds = commands(CURA_STYLE);
    h.control().clear_received();
    let (resends, timeouts) = h.stream(&cmds, Duration::from_secs(5));
    assert_eq!((resends, timeouts), (0, 0));
    assert_eq!(h.control().received_commands(), cmds);
    assert!(
        !h.log
            .iter()
            .any(|l| l.starts_with("echo:Unknown command") || l.starts_with("Error:")),
        "{:?}",
        h.log
    );
    // Absolute E: -4.50425 after the last layer, then -2 and -2 relative.
    let pos = h.command("M114");
    assert!(
        pos[0].starts_with("X:0.00 Y:200.00 Z:10.70 E:-8.50"),
        "{pos:?}"
    );
    // The M105s between the heat-ups were answered with temperatures.
    let temps = h.log.iter().filter(|l| l.starts_with("ok T:")).count();
    assert_eq!(temps, 2);
}

fn number(rng: &mut Rng) -> String {
    match rng.below(10) {
        0 => format!("{}", rng.below(300)),
        1 => format!("-{}", rng.below(50)),
        2 => format!("{}.{:03}", rng.below(250), rng.below(1000)),
        3 => format!(".{}", rng.below(99999)),
        4 => format!("-.{}", rng.below(999)),
        5 => format!("{}", rng.next()),
        6 => "0".to_string(),
        7 => format!("{}.{}", rng.below(10), rng.next()),
        8 => rng
            .pick(&[
                "1e30",
                "1e-30",
                "999999999999999999999999999",
                "-",
                "",
                "+5",
            ])
            .to_string(),
        _ => format!("{:.5}", (rng.below(100_000) as f64) / 1000.0),
    }
}

fn classic_line(rng: &mut Rng) -> String {
    let mut s = String::new();
    let numbered = rng.chance(15);
    if numbered {
        s.push_str(&format!("N{} ", rng.below(100_000)));
    }
    let mut code = rng.pick(CODES).to_string();
    if rng.chance(10) {
        code = code.to_lowercase();
    }
    s.push_str(&code);
    if ["M117", "M23", "M0", "M1"]
        .iter()
        .any(|c| code.eq_ignore_ascii_case(c))
    {
        s.push(' ');
        s.push_str(rng.pick(&[
            "Hello world",
            "file.gco",
            "a;b",
            "(x)",
            "50% done",
            "",
            "S30 Swap filament",
            "s5Done",
            "P1 p2 ",
        ]));
    }
    for _ in 0..rng.below(6) {
        if rng.chance(80) {
            s.push(' ');
        }
        s.push(*rng.pick(LETTERS));
        if rng.chance(90) {
            s.push_str(&number(rng));
        }
    }
    if numbered && rng.chance(70) {
        s.push_str(&format!("*{}", rng.below(300)));
    }
    if rng.chance(20) {
        s.push_str(" ; ");
        s.push_str(rng.pick(COMMENTS).trim_start_matches(';'));
    }
    s
}

fn junk_line(rng: &mut Rng) -> String {
    let mut s = String::new();
    for _ in 0..rng.below(12) {
        match rng.below(4) {
            0 => s.push_str(rng.pick(JUNK)),
            1 => s.push(*rng.pick(LETTERS)),
            2 => s.push_str(&number(rng)),
            _ => s.push_str(rng.pick(CODES)),
        }
    }
    s
}

fn random_line(rng: &mut Rng) -> String {
    match rng.below(10) {
        0..=4 => classic_line(rng),
        5 | 6 => rng.pick(COMMENTS).to_string(),
        7 => format!("{}{}", rng.pick(EXTENDED), number(rng)),
        _ => junk_line(rng),
    }
}

fn same_words(a: &ParsedLine<'_>, b: &ParsedLine<'_>) -> bool {
    a.words.len() == b.words.len()
        && a.words.iter().zip(&b.words).all(|(x, y)| {
            x.letter == y.letter && (x.value == y.value || x.value.is_nan() && y.value.is_nan())
        })
}

#[test]
fn lexer_invariants_hold_for_random_lines() {
    let mut rng = Rng::new(seed(1));
    let lines: Vec<String> = (0..30_000).map(|_| random_line(&mut rng)).collect();
    let mut reused = ParsedLine::default();
    let mut commands = 0;
    for line in &lines {
        let parsed = parse_line(line);
        parse_into(line, &mut reused);
        assert_eq!(parsed.code, reused.code, "{line:?}");
        assert_eq!(parsed.text, reused.text, "{line:?}");
        assert_eq!(parsed.comment, reused.comment, "{line:?}");
        assert!(same_words(&parsed, &reused), "{line:?}");
        for w in &parsed.words {
            assert!(w.letter.is_ascii_uppercase(), "{line:?}");
            assert!(w.value.is_finite() || w.value.is_nan(), "{line:?}");
        }
        let cleaned = clean_line(line);
        assert_eq!(has_command(line), cleaned.is_some(), "{line:?}");
        let Some(cleaned) = cleaned else {
            assert!(parsed.is_empty() && parsed.text.is_none(), "{line:?}");
            continue;
        };
        commands += 1;
        assert!(!cleaned.is_empty());
        assert_eq!(cleaned.trim(), &*cleaned, "{line:?}");
        // Idempotent and meaning-preserving.
        assert_eq!(clean_line(&cleaned).as_deref(), Some(&*cleaned), "{line:?}");
        let again = parse_line(&cleaned);
        assert_eq!(parsed.code, again.code, "{line:?} -> {cleaned:?}");
        assert_eq!(parsed.text, again.text, "{line:?} -> {cleaned:?}");
        assert!(same_words(&parsed, &again), "{line:?} -> {cleaned:?}");
    }
    assert!(commands > 15_000, "{commands}");
}

fn random_file(rng: &mut Rng, lines: usize) -> String {
    let mut text = String::new();
    // Most files start like a print so the analyzer goes deep.
    if rng.chance(70) {
        text.push_str("G28\nM83\nG1 Z0.2 F600\n");
    }
    for _ in 0..lines {
        if rng.chance(40) {
            // A plausible move to keep geometry flowing.
            let z = 0.2 * (1 + rng.below(5)) as f64;
            text.push_str(&format!(
                "G1 X{} Y{} Z{z:.1} E{}\n",
                rng.below(200),
                rng.below(200),
                number(rng)
            ));
        } else {
            text.push_str(&random_line(rng));
            text.push_str(rng.pick(&["\n", "\n", "\r\n", "\r"]));
        }
    }
    text
}

#[test]
fn analysis_never_panics_on_random_files() {
    let mut rng = Rng::new(seed(2));
    for i in 0..400 {
        let lines = rng.below(300);
        let text = random_file(&mut rng, lines);
        let file = GcodeFile::from_text(format!("fuzz-{i}.gcode"), text);
        let tp = analyze_simple(&file, &AnalyzeOptions::default());
        check_toolpath(&tp);
        let _ = read_metadata(&file);
        let line = rng.below(file.len() + 2);
        let state = state_at_line(&file, line);
        assert!(state.position.iter().all(|v| v.is_finite()));
        let options = ResumeOptions {
            home_z: rng.chance(30),
            restore_z_position: rng.chance(30),
            ..ResumeOptions::default()
        };
        for l in resume_preamble(&file, line, &options) {
            assert!(clean_line(&l).is_some(), "{l:?}");
            assert!(!l.contains("NaN") && !l.contains("inf"), "{l:?}");
        }
    }
}

#[test]
fn analysis_never_panics_on_random_bytes() {
    let mut rng = Rng::new(seed(3));
    let alphabet = b"G0123456789XYZEFIJRPSTMN .-;()*%\"\n\r\t";
    for i in 0..300 {
        let len = rng.below(3000);
        let bytes: Vec<u8> = (0..len)
            .map(|_| {
                if rng.chance(85) {
                    *rng.pick(alphabet)
                } else {
                    (rng.next() & 0xFF) as u8
                }
            })
            .collect();
        let file = GcodeFile::from_bytes(format!("bytes-{i}"), bytes.clone());
        // Line starts in the source are where the source's lines start.
        assert_eq!(file.source_len(), bytes.len() as u64);
        let mut previous = 0;
        for j in 0..file.len() {
            let at = file.source_offset(j);
            assert!(at >= previous && at <= file.source_len(), "{i}/{j}");
            let before = usize::try_from(at).ok().and_then(|a| a.checked_sub(1));
            assert!(
                before.is_none_or(|b| matches!(bytes.get(b), Some(b'\n' | b'\r'))),
                "{i}/{j}"
            );
            previous = at;
        }
        let mut cancel_after = rng.below(20);
        let result = analyze(&file, &AnalyzeOptions::default(), &mut |_| {
            cancel_after = cancel_after.saturating_sub(1);
            cancel_after > 0 || i % 2 == 0
        });
        if let Some(tp) = result {
            check_toolpath(&tp);
        }
        let _ = read_metadata(&file);
        for j in 0..file.len() {
            let _ = file.command(j);
        }
    }
}

#[test]
fn pathological_numbers_and_arcs_stay_bounded() {
    let text = "\
G28
G1 Z0.2 F600
M83
G2 X1e30 I1e-30 E1
G3 I0.0000001 J0 E1
G2 X10 R1e300 E1
G2 I1 P1e300 E1
G2 I5 J5 P-3 E1
G1 X99999999999999999999 E1
G1 Y-99999999999999999999 E1
G91
G1 X99999999999999999 E99999999999999999
G1 X99999999999999999 E99999999999999999
G90
G4 P99999999999999999999
G4 S-5
M204 S0
M203 X0
M201 X0 Y0
M205 J0 X0 Y0
G1 X0 Y0 F0.0000001 E1
G92 X1e300
G1 X5 E1
G1 F-100
M220 S0.0001
G1 X10 E1
";
    let file = GcodeFile::from_text("pathological", text);
    let tp = analyze_simple(&file, &AnalyzeOptions::default());
    check_toolpath(&tp);
    assert!(tp.segments.len() < 50_000);
    assert!(tp.stats.estimated_time.is_finite());
    let bad = AnalyzeOptions {
        filament_diameter: f32::NAN,
        filament_density: -1.0,
        arc_tolerance: f32::INFINITY,
        ..AnalyzeOptions::default()
    };
    let tp = analyze_simple(&file, &bad);
    check_toolpath(&tp);
    assert!(tp.stats.filament_weight.is_finite());
}

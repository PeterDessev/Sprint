    let m = &tp.metadata;
    assert_eq!(m.slicer.as_deref(), Some("Simplify3D 4.1.2"));
    assert_eq!(m.estimated_time, Some(60.0));
    assert_eq!(m.filament_used_mm, Some(3.4));
    assert_eq!(m.filament_density, Some(1.25));
    assert_eq!(m.object_names, ["cube"]);
    assert_eq!(tp.layers.len(), 2);
    assert_eq!(
        extrusion_features(&tp, 0),
        [Feature::Skirt, Feature::ExternalPerimeter]
    );
    let infill = tp
        .segments
        .iter()
        .find(|s| s.feature == Feature::InternalInfill);
    assert_eq!(infill.map(|s| (s.width, s.height)), Some((0.5, 0.2)));
    assert_eq!(tp.stats.hotend_temps, [(0, 210.0)]);

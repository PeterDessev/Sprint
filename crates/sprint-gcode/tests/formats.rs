//! End-to-end checks over short files written the way the supported slicers
//! and firmwares write them: lexer, analysis, metadata and resume together.

mod common;

use common::check_toolpath;
use sprint_gcode::{
    AnalyzeOptions, Feature, GcodeFile, ResumeOptions, Toolpath, analyze_simple, clean_line,
    parse_line, read_metadata, resume_preamble,
};

fn analyzed(text: &str) -> (GcodeFile, Toolpath) {
    let file = GcodeFile::from_text("t.gcode", text);
    let tp = analyze_simple(&file, &AnalyzeOptions::default());
    check_toolpath(&tp);
    (file, tp)
}

fn extrusion_features(tp: &Toolpath, layer: usize) -> Vec<Feature> {
    let mut out: Vec<Feature> = Vec::new();
    for s in &tp.segments[tp.layers[layer].segments.clone()] {
        if s.is_extrusion() && out.last() != Some(&s.feature) {
            out.push(s.feature);
        }
    }
    out
}


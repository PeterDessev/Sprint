#[test]
fn prusaslicer_mk3s() {
    let (file, tp) = analyzed(PRUSA);
    assert_eq!(
        tp.metadata.slicer.as_deref(),
        Some("PrusaSlicer 2.7.1"),
        "{:?}",
        tp.metadata
    );
    assert_eq!(tp.metadata.estimated_time, Some(65.0));
    assert_eq!(tp.metadata.filament_used_g, Some(0.05));
    assert_eq!(tp.metadata.settings.len(), 4);
    // The intro line at Z0.2 joins the first layer; the hops make no layers.
    assert_eq!(tp.layers.len(), 2);
    assert_eq!(
        extrusion_features(&tp, 0),
        [Feature::Custom, Feature::Skirt, Feature::ExternalPerimeter]
    );
    assert_eq!(extrusion_features(&tp, 1), [Feature::InternalInfill]);
    let skirt = tp.segments.iter().find(|s| s.feature == Feature::Skirt);
    assert_eq!(skirt.map(|s| (s.width, s.height)), Some((0.42, 0.2)));
    // The wipe is a travel and the E-only moves are retraction markers.
    let amounts: Vec<f32> = tp.retractions.iter().map(|r| r.amount).collect();
    assert_eq!(amounts, [-0.8, 0.8, -0.5, 0.8]);
    assert_eq!(tp.stats.retractions, 2);
    assert!(tp.stats.uses_relative_e);
    assert_eq!(tp.stats.heat_waits, 2);
    assert_eq!(tp.stats.hotend_temps, [(0, 215.0)]);
    // Quoted printer checks are sent verbatim.
    assert_eq!(
        clean_line("M862.3 P \"MK3S\" ; printer model check").as_deref(),
        Some("M862.3 P \"MK3S\"")
    );
    // Resume on the second layer: G80 is not Marlin leveling, Z is not
    // homed, and the flow override from the start G-code is restored.
    let line = file
        .lines()
        .position(|l| l == "G1 X105 Y105 E.5")
        .unwrap_or_default();
    let pre = resume_preamble(&file, line, &ResumeOptions::default());
    assert!(pre.contains(&"G28 X Y".to_string()), "{pre:?}");
    assert!(pre.contains(&"M221 S95".to_string()), "{pre:?}");
    assert!(pre.contains(&"M83".to_string()), "{pre:?}");
    assert!(!pre.iter().any(|l| l == "M420 S1" || l == "G28"), "{pre:?}");
}


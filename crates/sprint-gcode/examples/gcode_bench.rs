//! Throughput benchmark: builds a large synthetic print in memory (~2M
//! lines of PrusaSlicer-style G-code) and times loading, parsing, cleaning,
//! metadata scanning and full analysis.
//!
//! Run in release mode:
//!
//! ```text
//! cargo run --release -p sprint-gcode --example gcode_bench
//! ```

use std::fmt::Write as _;
use std::hint::black_box;
use std::time::{Duration, Instant};

use sprint_gcode::{
    AnalyzeOptions, GcodeFile, ParsedLine, Segment, analyze, parse_into, read_metadata,
};

const TARGET_LINES: usize = 2_000_000;

/// A synthetic multi-layer print: perimeters made of many short segments,
/// rectilinear infill, retractions with Z hops and slicer annotations.
fn build_text() -> String {
    let mut s = String::with_capacity(TARGET_LINES * 32);
    s.push_str("; generated by PrusaSlicer 2.7.1+win64 on 2024-01-15 at 10:00:00 UTC\n");
    s.push_str("M201 X1000 Y1000 Z200 E5000\nM203 X200 Y200 Z12 E120\nM204 P1250 R1250 T1250\n");
    s.push_str(
        "M205 X8.00 Y8.00 Z0.40 E4.50\nG90\nM83\nM104 S215\nM140 S60\nM190 S60\nM109 S215\nG28\n",
    );
    let mut lines = 13usize;
    let mut layer = 0usize;
    while lines < TARGET_LINES {
        layer += 1;
        let z = layer as f64 * 0.2;
        let _ = write!(
            s,
            ";LAYER_CHANGE\n;Z:{z:.1}\n;HEIGHT:0.2\nG1 E-.8 F2100\nG1 Z{:.1} F10800\nG1 X150 Y110\nG1 Z{z:.1}\nG1 E.8 F2100\n",
            z + 0.4
        );
        lines += 8;
        for (feature, radius) in [("Perimeter", 39.55), ("External perimeter", 40.0)] {
            let _ = writeln!(s, ";TYPE:{feature}\n;WIDTH:0.45\nG1 F1800");
            lines += 3;
            for k in 0..=360 {
                let a = (k as f64).to_radians();
                let _ = writeln!(
                    s,
                    "G1 X{:.3} Y{:.3} E.02963",
                    110.0 + radius * a.cos(),
                    110.0 + radius * a.sin()
                );
                lines += 1;
            }
        }
        let _ = writeln!(s, ";TYPE:Internal infill\n;WIDTH:0.5\nG1 F6000");
        lines += 3;
        for i in 0..70 {
            let y = 75.0 + i as f64;
            let (x0, x1) = if i % 2 == 0 {
                (75.0, 145.0)
            } else {
                (145.0, 75.0)
            };
            let _ = writeln!(s, "G1 X{x0:.3} Y{y:.3}\nG1 X{x1:.3} Y{y:.3} E2.30142");
            lines += 2;
        }
    }
    s.push_str("M104 S0\nM140 S0\nM107\nG1 X0 Y200 F3000\nM84\n");
    s
}

fn rate(count: usize, d: Duration) -> String {
    let secs = d.as_secs_f64().max(1e-9);
    let per_sec = count as f64 / secs;
    if per_sec >= 1e6 {
        format!("{:.2} M/s", per_sec / 1e6)
    } else {
        format!("{:.0} k/s", per_sec / 1e3)
    }
}

fn mb_rate(bytes: usize, d: Duration) -> String {
    format!("{:.0} MB/s", bytes as f64 / 1e6 / d.as_secs_f64().max(1e-9))
}

/// Best of `n` runs.
fn best<T>(n: usize, mut f: impl FnMut() -> T) -> (Duration, T) {
    let mut best = Duration::MAX;
    let mut out = None;
    for _ in 0..n {
        let t = Instant::now();
        let v = f();
        best = best.min(t.elapsed());
        out = Some(v);
    }
    match out {
        Some(v) => (best, v),
        None => (best, f()),
    }
}

fn main() {
    let t = Instant::now();
    let text = build_text();
    let build = t.elapsed();
    let bytes = text.len();
    println!(
        "synthetic file: {:.1} MB, built in {:.0} ms",
        bytes as f64 / 1e6,
        build.as_secs_f64() * 1e3
    );

    let (load, file) = best(3, || GcodeFile::from_text("bench.gcode", text.clone()));
    let n = file.len();
    println!(
        "load (index lines, count commands):  {:>8.1} ms  {:>10}  {}",
        load.as_secs_f64() * 1e3,
        rate(n, load),
        mb_rate(bytes, load)
    );

    let path =
        std::env::temp_dir().join(format!("sprint-gcode-bench-{}.gcode", std::process::id()));
    if std::fs::write(&path, &text).is_ok() {
        let (disk, loaded) = best(3, || GcodeFile::load(&path));
        if let Ok(f) = loaded {
            println!(
                "load from disk (read + lossy UTF-8 + index): {:.1} ms  {}  ({} lines)",
                disk.as_secs_f64() * 1e3,
                mb_rate(bytes, disk),
                f.len()
            );
        }
        let _ = std::fs::remove_file(&path);
    }

    let (parse, words) = best(5, || {
        let mut parsed = ParsedLine::default();
        let mut words = 0usize;
        for line in file.lines() {
            parse_into(line, &mut parsed);
            words += parsed.words.len();
        }
        black_box(words)
    });
    println!(
        "parse_into (no allocation):          {:>8.1} ms  {:>10}  ({words} words)",
        parse.as_secs_f64() * 1e3,
        rate(n, parse)
    );

    let (clean, sent) = best(3, || {
        let mut total = 0usize;
        for i in 0..n {
            if let Some(c) = file.command(i) {
                total += c.len();
            }
        }
        black_box(total)
    });
    println!(
        "clean_line (command to send):        {:>8.1} ms  {:>10}  ({sent} bytes to send)",
        clean.as_secs_f64() * 1e3,
        rate(n, clean)
    );

    let (meta, m) = best(5, || read_metadata(&file));
    println!(
        "read_metadata:                       {:>8.2} ms  (slicer {:?})",
        meta.as_secs_f64() * 1e3,
        m.slicer
    );

    let options = AnalyzeOptions::default();
    let (an, tp) = best(3, || analyze(&file, &options, &mut |_| true));
    if let Some(tp) = tp {
        let seg_bytes = tp.segments.len() * std::mem::size_of::<Segment>();
        println!(
            "analyze (toolpath + planner + stats): {:>7.1} ms  {:>10}  {}",
            an.as_secs_f64() * 1e3,
            rate(n, an),
            mb_rate(bytes, an)
        );
        println!(
            "  {} segments ({} bytes each, {:.0} MB), {} layers, {} retractions",
            tp.segments.len(),
            std::mem::size_of::<Segment>(),
            seg_bytes as f64 / 1e6,
            tp.layers.len(),
            tp.retractions.len()
        );
        println!(
            "  estimated print time {:.1} h, filament {:.1} m",
            tp.stats.estimated_time / 3600.0,
            tp.stats.filament_length / 1000.0
        );
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use ratatui::Terminal;
    use ratatui::backend::TestBackend;

    fn screen(demo: &mut Demo, width: u16, height: u16) -> String {
        let mut terminal = Terminal::new(TestBackend::new(width, height)).expect("terminal");
        terminal.draw(|frame| demo.draw(frame)).expect("draw");
        let buf = terminal.backend().buffer();
        (0..height)
            .map(|y| (0..width).map(|x| buf[(x, y)].symbol()).collect::<String>())
            .collect::<Vec<_>>()
            .join("\n")
    }

    fn press(demo: &mut Demo, code: KeyCode) {
        demo.on_key(KeyEvent::new(code, KeyModifiers::NONE));
    }

    #[test]
    fn demo_prints_and_draws_every_screen() {
        let (name, toolpath) = load_toolpath();
        let mut demo = Demo::new(name, toolpath);
        let text = screen(&mut demo, 120, 40);
        assert!(text.contains("Heating"), "{text}");
        for _ in 0..400 {
            demo.step();
        }
        assert!(demo.line.is_some(), "the print starts once heated");
        let text = screen(&mut demo, 120, 40);
        assert!(text.contains("Printing"), "{text}");
        assert!(text.contains("Layer "), "{text}");
        assert!(text.contains("T0"), "{text}");
        press(&mut demo, KeyCode::Tab);
        let text = screen(&mut demo, 120, 40);
        assert!(text.contains("Print time"), "{text}");
        press(&mut demo, KeyCode::Char('?'));
        let text = screen(&mut demo, 120, 40);
        assert!(text.contains("Command line"), "{text}");
        press(&mut demo, KeyCode::Esc);
        assert!(!demo.help);
        // Tiny and odd sizes do not panic.
        for (w, h) in [(1, 1), (20, 5), (60, 12), (300, 80)] {
            let _ = screen(&mut demo, w, h);
        }
        for _ in 0..(PRINT_STEPS + 100) {
            demo.step();
        }
        assert!(
            demo.done,
            "line {:?} of {}",
            demo.line, demo.toolpath.line_count
        );
        press(&mut demo, KeyCode::Char('1'));
        assert!(screen(&mut demo, 120, 40).contains("Completed"));
    }

    #[test]
    fn command_line_completes_and_sends() {
        let (name, toolpath) = load_toolpath();
        let mut demo = Demo::new(name, toolpath);
        press(&mut demo, KeyCode::Char(':'));
        assert_eq!(demo.focus, Focus::Command);
        for c in "m14".chars() {
            press(&mut demo, KeyCode::Char(c));
        }
        press(&mut demo, KeyCode::Tab);
        assert!(demo.command.is_completing());
        let text = screen(&mut demo, 120, 40);
        assert!(text.contains("M140"), "{text}");
        press(&mut demo, KeyCode::Enter);
        assert!(demo.command.text().starts_with("M14"));
        demo.command.set_text("M140 S80");
        press(&mut demo, KeyCode::Enter);
        assert_eq!(demo.bed.target, 80.0);
        assert!(demo.console.iter().any(|l| l.text == "M140 S80"));
        press(&mut demo, KeyCode::Esc);
        assert_eq!(demo.focus, Focus::View);
        // Search highlights and counts matches.
        press(&mut demo, KeyCode::Char('/'));
        for c in "ok".chars() {
            press(&mut demo, KeyCode::Char(c));
        }
        press(&mut demo, KeyCode::Enter);
        assert_eq!(demo.search, "ok");
        assert!(screen(&mut demo, 120, 40).contains("matches"));
        press(&mut demo, KeyCode::Char('q'));
        assert!(demo.quit);
    }

    #[test]
    fn synthetic_part_has_layers() {
        let file = GcodeFile::from_text("synthetic.gcode", synthetic_gcode());
        let toolpath = analyze_simple(&file, &AnalyzeOptions::default());
        assert_eq!(toolpath.layers.len(), 30);
        let mut demo = Demo::new("synthetic.gcode".to_string(), toolpath);
        for _ in 0..300 {
            demo.step();
        }
        let _ = screen(&mut demo, 100, 30);
    }
}

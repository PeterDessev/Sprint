//! Full-screen demo of the Sprint terminal widgets, driven by synthetic
//! data: a simulated print of the sample calibration cube (or a generated
//! part when the sample is missing), heating curves, console traffic and a
//! working command line with G-code completion.
//!
//! ```text
//! cargo run -p sprint-tui --example widgets_demo
//! ```
//!
//! Press `q` (or Ctrl+C) to quit and `?` for the keys. Nothing here talks
//! to a printer.

use std::io;
use std::time::{Duration, Instant};

use crossterm::event::{
    self, DisableMouseCapture, EnableMouseCapture, Event, KeyCode, KeyEvent, KeyEventKind,
    KeyModifiers,
};
use crossterm::execute;
use ratatui::layout::{Constraint, Layout, Rect};
use ratatui::text::{Line, Span};
use ratatui::widgets::{Block, Clear, Paragraph};
use ratatui::{DefaultTerminal, Frame};
use sprint_gcode::{AnalyzeOptions, Bounds, GcodeFile, Toolpath, analyze_simple, parse_line};
use sprint_tui::{
    CommandInput, CommandLine, CompletionPopup, ConsoleLine, ConsoleState, ConsoleView,
    FeatureLegend, HeaterGauge, HeaterKind, HelpOverlay, HelpSection, InputEvent, JobProgress,
    JobTone, KeyHints, LayerCanvas, LayerFit, StatsPanel, TempChart, TempPoint, Theme,
    object_bounds,
};

/// Real time per simulation step.
const TICK: Duration = Duration::from_millis(100);
/// Simulated seconds per step.
const SIM_STEP: f64 = 1.0;
/// Temperature history kept, in samples.
const HISTORY: usize = 1800;
/// Console lines kept.
const CONSOLE_MAX: usize = 2000;
/// The demo print lasts about this many steps.
const PRINT_STEPS: u32 = 2400;

fn main() -> io::Result<()> {
    let (name, toolpath) = load_toolpath();
    let mut terminal = ratatui::try_init()?;
    let mouse = execute!(io::stdout(), EnableMouseCapture).is_ok();
    let result = Demo::new(name, toolpath).run(&mut terminal);
    if mouse {
        let _ = execute!(io::stdout(), DisableMouseCapture);
    }
    ratatui::restore();
    result
}

/// The sample cube when it can be read, else a generated part.
fn load_toolpath() -> (String, Toolpath) {
    let sample = concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/../../samples/calibration-cube.gcode"
    );
    let file = GcodeFile::load(sample)
        .unwrap_or_else(|_| GcodeFile::from_text("synthetic-part.gcode", synthetic_gcode()));
    let toolpath = analyze_simple(&file, &AnalyzeOptions::default());
    (file.name().to_string(), toolpath)
}

/// A 30-layer square tube with diagonal infill, PrusaSlicer style.
fn synthetic_gcode() -> String {
    let mut g = String::from(
        "; generated by the Sprint widgets demo\nM140 S60\nM104 S210\nM190 S60\nM109 S210\n\
         G28\nG90\nM83\n",
    );
    for layer in 1..=30 {
        let z = f64::from(layer) * 0.2;
        g.push_str(&format!(";LAYER_CHANGE\n;Z:{z:.1}\nG1 Z{z:.1} F600\n"));
        g.push_str("G1 X100 Y100 F9000\n;TYPE:External perimeter\n");
        for (x, y) in [(130, 100), (130, 130), (100, 130), (100, 100)] {
            g.push_str(&format!("G1 X{x} Y{y} E1.2 F1800\n"));
        }
        g.push_str(";TYPE:Internal infill\n");
        for i in 0..6 {
            let a = 102 + i * 5;
            let (x0, y0, x1, y1) = if layer % 2 == 0 {
                (a, 102, 128, 128 - (a - 102))
            } else {
                (102, a, 128 - (a - 102), 128)
            };
            g.push_str(&format!(
                "G1 X{x0} Y{y0} F9000\nG1 X{x1} Y{y1} E0.8 F3000\n"
            ));
        }
    }
    g.push_str("M104 S0\nM140 S0\nM84\n");
    g
}

/// Which input line has the keyboard.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Focus {
    View,
    Command,
    Search,
}

/// A first-order heater: approaches its target with some overshoot-free
/// lag, reporting a plausible power.
#[derive(Clone, Copy, Debug)]
struct Heater {
    current: f32,
    target: f32,
    power: f32,
    rate: f32,
}

impl Heater {
    fn step(&mut self, ambient: f32, wobble: f32) {
        let goal = if self.target > 0.0 {
            self.target
        } else {
            ambient
        };
        let error = goal - self.current;
        self.current += error * self.rate + wobble;
        self.power = if self.target > 0.0 {
            (error / 15.0 + 0.25).clamp(0.0, 1.0)
        } else {
            0.0
        };
    }

    fn ready(&self) -> bool {
        self.target > 0.0 && (self.current - self.target).abs() < 2.0
    }
}

struct Demo {
    theme: Theme,
    name: String,
    toolpath: Toolpath,
    bounds: Bounds,
    /// Source line printed up to; `None` before the print starts.
    line: Option<u32>,
    lines_per_step: u32,
    /// Simulated print time so far, seconds.
    print_time: f64,
    done: bool,
    paused: bool,
    /// Layer chosen by the user; `None` follows the print.
    layer_view: Option<usize>,
    fit: LayerFit,
    t: f64,
    hotend: Heater,
    bed: Heater,
    temps: Vec<TempPoint>,
    console: Vec<ConsoleLine>,
    console_state: ConsoleState,
    show_auto: bool,
    search: String,
    command: CommandInput,
    search_input: CommandInput,
    focus: Focus,
    tab: usize,
    help: bool,
    stats_scroll: usize,
    quit: bool,
}

impl Demo {
    fn new(name: String, toolpath: Toolpath) -> Demo {
        let bounds = object_bounds(&toolpath);
        let lines_per_step = toolpath.line_count.div_ceil(PRINT_STEPS).max(1);
        let mut demo = Demo {
            theme: Theme::detect(),
            name,
            toolpath,
            bounds,
            line: None,
            lines_per_step,
            print_time: 0.0,
            done: false,
            paused: false,
            layer_view: None,
            fit: LayerFit::Object,
            t: 0.0,
            hotend: Heater {
                current: 22.0,
                target: 210.0,
                power: 0.0,
                rate: 0.035,
            },
            bed: Heater {
                current: 22.0,
                target: 60.0,
                power: 0.0,
                rate: 0.05,
            },
            temps: Vec::new(),
            console: Vec::new(),
            console_state: ConsoleState::new(),
            show_auto: false,
            search: String::new(),
            command: CommandInput::new(),
            search_input: CommandInput::new().with_completer(|_| Vec::new()),
            focus: Focus::View,
            tab: 0,
            help: false,
            stats_scroll: 0,
            quit: false,
        };
        demo.log(ConsoleLine::info(
            "Connected to the demo printer (simulated)",
        ));
        demo.log(ConsoleLine::received(
            "FIRMWARE_NAME:Marlin 2.1.2 (Demo) MACHINE_TYPE:Sprint Virtual Printer EXTRUDER_COUNT:1",
        ));
        for cmd in ["M140 S60", "M104 S210"] {
            demo.log(ConsoleLine::sent(cmd));
            demo.log(ConsoleLine::received("ok"));
        }
        demo.log(ConsoleLine::info("Heating up before the print starts"));
        demo
    }

    fn run(&mut self, terminal: &mut DefaultTerminal) -> io::Result<()> {
        let mut next = Instant::now();
        while !self.quit {
            terminal.draw(|frame| self.draw(frame))?;
            let timeout = next.saturating_duration_since(Instant::now());
            if event::poll(timeout)? {
                match event::read()? {
                    Event::Key(key) => self.on_key(key),
                    Event::Mouse(mouse) if self.tab == 0 => {
                        self.console_state.handle_mouse(mouse);
                    }
                    Event::Paste(text) => match self.focus {
                        Focus::Command => self.command.insert_str(&text),
                        Focus::Search => self.search_input.insert_str(&text),
                        Focus::View => {}
                    },
                    _ => {}
                }
            }
            if Instant::now() >= next {
                self.step();
                next += TICK;
                // After a stall, do not try to catch up.
                if next < Instant::now() {
                    next = Instant::now() + TICK;
                }
            }
        }
        Ok(())
    }

    fn log(&mut self, line: ConsoleLine) {
        self.console.push(line);
        let excess = self.console.len().saturating_sub(CONSOLE_MAX);
        if excess > 0 {
            self.console.drain(..excess);
            // A scrolled-back console stays on its lines.
            self.console_state.lines_removed(excess);
        }
    }

    /// Advance the simulation by one step.
    fn step(&mut self) {
        self.t += SIM_STEP;
        let wobble = ((self.t * 1.7).sin() * 0.15) as f32;
        self.hotend.step(22.0, wobble);
        self.bed.step(22.0, wobble * 0.3);
        self.temps.push(TempPoint {
            t: self.t,
            hotends: vec![(self.hotend.current, self.hotend.target)],
            bed: Some((self.bed.current, self.bed.target)),
            chamber: None,
        });
        let excess = self.temps.len().saturating_sub(HISTORY);
        if excess > 0 {
            self.temps.drain(..excess);
        }
        if (self.t as u64).is_multiple_of(2) {
            let report = format!(
                "ok T:{:.1} /{:.1} B:{:.1} /{:.1} @:{:.0} B@:{:.0}",
                self.hotend.current,
                self.hotend.target,
                self.bed.current,
                self.bed.target,
                self.hotend.power * 127.0,
                self.bed.power * 127.0
            );
            self.log(ConsoleLine::sent("M105").with_auto(true));
            self.log(ConsoleLine::received(report).with_auto(true));
        }
        if self.paused || self.done {
            return;
        }
        match self.line {
            None if self.hotend.ready() && self.bed.ready() => {
                self.line = Some(0);
                self.print_time = 0.0;
                self.log(ConsoleLine::info(format!("Printing {}", self.name)));
            }
            None => {}
            Some(line) => {
                let layer_before = self.toolpath.layer_at_line(line);
                let Some(next) = self.advance(line) else {
                    self.line = Some(self.toolpath.line_count.saturating_sub(1));
                    self.done = true;
                    self.log(ConsoleLine::info("Print finished"));
                    return;
                };
                self.line = Some(next);
                let layer_after = self.toolpath.layer_at_line(next);
                if layer_after != layer_before
                    && let Some(layer) = layer_after
                {
                    let total = self.toolpath.layers.len();
                    self.log(ConsoleLine::sent(format!(
                        "M117 Layer {}/{total}",
                        layer + 1
                    )));
                    self.log(ConsoleLine::received("ok"));
                }
            }
        }
    }

    /// Move the print on by one step: through the estimated print time
    /// (so progress is smooth), or by lines for toolpaths without times.
    /// `None` once the print is over.
    fn advance(&mut self, line: u32) -> Option<u32> {
        let total = f64::from(self.toolpath.stats.estimated_time);
        if total.is_finite() && total > 0.0 {
            self.print_time += total / f64::from(PRINT_STEPS);
            if self.print_time >= total {
                return None;
            }
            let print_time = self.print_time;
            let segments = &self.toolpath.segments;
            let i = segments.partition_point(|s| f64::from(s.time + s.duration) <= print_time);
            Some(segments.get(i).map_or(line, |s| s.line.max(line)))
        } else {
            self.print_time += SIM_STEP;
            let next = line.saturating_add(self.lines_per_step);
            (next < self.toolpath.line_count).then_some(next)
        }
    }

    fn current_layer(&self) -> usize {
        self.line
            .and_then(|l| self.toolpath.layer_at_line(l))
            .unwrap_or(0)
    }

    fn on_key(&mut self, key: KeyEvent) {
        if key.kind == KeyEventKind::Release {
            return;
        }
        if key.code == KeyCode::Char('c') && key.modifiers.contains(KeyModifiers::CONTROL) {
            self.quit = true;
            return;
        }
        if self.help {
            if matches!(key.code, KeyCode::Esc | KeyCode::Char('?' | 'q')) {
                self.help = false;
            }
            return;
        }
        match self.focus {
            Focus::Command => self.on_command_key(key),
            Focus::Search => self.on_search_key(key),
            Focus::View => self.on_view_key(key),
        }
    }

    fn on_command_key(&mut self, key: KeyEvent) {
        match self.command.handle_key(key) {
            InputEvent::Submitted(cmd) => self.run_command(&cmd),
            InputEvent::Handled => {}
            InputEvent::Ignored => {
                if key.code == KeyCode::Esc {
                    self.focus = Focus::View;
                } else {
                    self.console_state.handle_key(key);
                }
            }
        }
    }

    fn on_search_key(&mut self, key: KeyEvent) {
        match self.search_input.handle_key(key) {
            InputEvent::Submitted(text) => {
                self.search = text;
                self.focus = Focus::View;
            }
            InputEvent::Handled => {
                // Enter on an empty line clears the search.
                if key.code == KeyCode::Enter {
                    self.search.clear();
                    self.focus = Focus::View;
                }
            }
            InputEvent::Ignored => {
                if key.code == KeyCode::Esc {
                    self.focus = Focus::View;
                }
            }
        }
    }

    fn on_view_key(&mut self, key: KeyEvent) {
        if self.tab == 0 && self.console_state.handle_key(key) {
            return;
        }
        let layers = self.toolpath.layers.len();
        match key.code {
            KeyCode::Char('q') => self.quit = true,
            KeyCode::Char('?') => self.help = true,
            KeyCode::Tab | KeyCode::Char('1' | '2') => {
                self.tab = match key.code {
                    KeyCode::Char('1') => 0,
                    KeyCode::Char('2') => 1,
                    _ => 1 - self.tab,
                };
            }
            KeyCode::Char(':' | 'i') => self.focus = Focus::Command,
            KeyCode::Char('/') => {
                self.search_input.set_text(&self.search);
                self.focus = Focus::Search;
            }
            KeyCode::Char('a') => self.show_auto = !self.show_auto,
            KeyCode::Char('p') if !self.done => {
                self.paused = !self.paused;
                let text = if self.paused { "Paused" } else { "Resumed" };
                self.log(ConsoleLine::warning(text));
            }
            KeyCode::Char('b') => {
                self.fit = match self.fit {
                    LayerFit::Bed => LayerFit::Object,
                    LayerFit::Object => LayerFit::Bed,
                };
            }
            KeyCode::Char('[') | KeyCode::Left if layers > 0 => {
                let layer = self.layer_view.unwrap_or_else(|| self.current_layer());
                self.layer_view = Some(layer.saturating_sub(1));
            }
            KeyCode::Char(']') | KeyCode::Right if layers > 0 => {
                let layer = self.layer_view.unwrap_or_else(|| self.current_layer());
                self.layer_view = Some((layer + 1).min(layers - 1));
            }
            KeyCode::Char('f') => self.layer_view = None,
            KeyCode::Up if self.tab == 1 => self.stats_scroll = self.stats_scroll.saturating_sub(1),
            KeyCode::Down if self.tab == 1 => self.stats_scroll += 1,
            _ => {}
        }
    }

    /// Pretend to send a command: echo it with a reply, honouring
    /// temperature commands.
    fn run_command(&mut self, cmd: &str) {
        self.log(ConsoleLine::sent(cmd));
        let parsed = parse_line(cmd);
        let target = parsed.get('S').map(|s| s as f32).filter(|s| s.is_finite());
        match parsed.code {
            Some(code) if code.is('M', 104) || code.is('M', 109) => {
                self.hotend.target = target.unwrap_or(0.0).clamp(0.0, 300.0);
                self.log(ConsoleLine::received("ok"));
            }
            Some(code) if code.is('M', 140) || code.is('M', 190) => {
                self.bed.target = target.unwrap_or(0.0).clamp(0.0, 120.0);
                self.log(ConsoleLine::received("ok"));
            }
            Some(code) if code.is('M', 112) => {
                self.log(ConsoleLine::error("Error:Printer halted. kill() called!"));
                self.paused = true;
            }
            Some(code) if code.is('M', 115) => {
                self.log(ConsoleLine::received(
                    "FIRMWARE_NAME:Marlin 2.1.2 (Demo) MACHINE_TYPE:Sprint Virtual Printer",
                ));
                self.log(ConsoleLine::received("ok"));
            }
            Some(_) => self.log(ConsoleLine::received("ok")),
            None => self.log(ConsoleLine::received(format!(
                "echo:Unknown command: \"{cmd}\""
            ))),
        }
    }

    fn draw(&mut self, frame: &mut Frame) {
        let area = frame.area();
        frame.render_widget(Block::new().style(self.theme.base()), area);
        let [header, body, hints] = Layout::vertical([
            Constraint::Length(1),
            Constraint::Fill(1),
            Constraint::Length(1),
        ])
        .areas(area);
        self.draw_header(frame, header);
        if self.tab == 0 {
            self.draw_live(frame, body);
        } else {
            self.draw_stats(frame, body);
        }
        frame.render_widget(KeyHints::new(self.hints()).theme(&self.theme), hints);
        if self.help {
            let sections = help_sections();
            frame.render_widget(
                HelpOverlay::new(&sections)
                    .title("Sprint widgets demo")
                    .footer(Some("Esc or ? closes".into()))
                    .theme(&self.theme),
                area,
            );
        }
    }

    fn draw_header(&self, frame: &mut Frame, area: Rect) {
        let theme = &self.theme;
        let tab = |i: usize, name: &'static str| {
            if self.tab == i {
                Span::styled(format!(" {name} "), theme.selected())
            } else {
                Span::styled(format!(" {name} "), theme.dim())
            }
        };
        let line = Line::from(vec![
            Span::styled(" Sprint ", theme.accent()),
            Span::styled("widgets demo  ", theme.dim()),
            tab(0, "1 Live"),
            Span::raw(" "),
            tab(1, "2 Statistics"),
        ]);
        frame.render_widget(Paragraph::new(line), area);
    }

    fn hints(&self) -> Vec<(&'static str, &'static str)> {
        match self.focus {
            Focus::Command if self.command.is_completing() => {
                vec![("Tab/↑↓", "Choose"), ("Enter", "Accept"), ("Esc", "Close")]
            }
            Focus::Command => vec![
                ("Enter", "Send"),
                ("Tab", "Complete"),
                ("↑↓", "History"),
                ("PgUp/PgDn", "Scroll"),
                ("Esc", "Leave"),
            ],
            Focus::Search => vec![("Enter", "Search"), ("Esc", "Cancel")],
            Focus::View if self.tab == 1 => vec![
                ("q", "Quit"),
                ("Tab", "Live view"),
                ("↑↓", "Scroll"),
                ("?", "Help"),
            ],
            Focus::View => vec![
                ("q", "Quit"),
                (":", "Command"),
                ("/", "Search"),
                ("[ ]", "Layer"),
                ("f", "Follow"),
                ("p", "Pause"),
                ("a", "Auto traffic"),
                ("Tab", "Statistics"),
                ("?", "Help"),
            ],
        }
    }

    fn draw_live(&mut self, frame: &mut Frame, area: Rect) {
        let theme = &self.theme;
        let [left, right] =
            Layout::horizontal([Constraint::Percentage(55), Constraint::Percentage(45)])
                .areas(area);
        let [canvas_area, legend_area, job_area] = Layout::vertical([
            Constraint::Fill(1),
            Constraint::Length(2),
            Constraint::Length(5),
        ])
        .areas(left);
        let [chart_area, heaters_area, console_area, input_area] = Layout::vertical([
            Constraint::Percentage(40),
            Constraint::Length(4),
            Constraint::Fill(1),
            Constraint::Length(3),
        ])
        .areas(right);

        // Layer view.
        let current = self.current_layer();
        let shown = self.layer_view.unwrap_or(current);
        let progress = if self.done {
            None
        } else {
            Some(self.line.unwrap_or(0))
        };
        let canvas = LayerCanvas::new(&self.toolpath, shown, progress, [250.0, 210.0])
            .fit(self.fit)
            .object_bounds(self.bounds)
            .show_tool(shown == current && self.line.is_some())
            .theme(theme);
        let follow = if self.layer_view.is_some() {
            ""
        } else {
            " (following)"
        };
        let title = format!(" {}{follow} ", canvas.label_text());
        frame.render_widget(
            canvas.block(
                Block::bordered()
                    .title(Span::styled(title, theme.title()))
                    .border_style(theme.border(false)),
            ),
            canvas_area,
        );
        frame.render_widget(
            FeatureLegend::new(&self.toolpath, Some(shown)).theme(theme),
            legend_area,
        );

        // Job.
        // Simulated print time stands in for the clock.
        let elapsed = self
            .line
            .map(|_| Duration::from_secs_f64(self.print_time.max(0.0)));
        let progress = match self.line {
            _ if self.done => 1.0,
            Some(l) => self.toolpath.progress_at_line(l),
            None => 0.0,
        };
        let total = f64::from(self.toolpath.stats.estimated_time);
        let eta = (self.line.is_some() && total.is_finite() && total > 0.0)
            .then(|| Duration::from_secs_f64((total - self.print_time).max(0.0)));
        let (status, tone) = match (self.line, self.done, self.paused) {
            (_, true, _) => ("Completed", JobTone::Done),
            (_, _, true) => ("Paused", JobTone::Paused),
            (None, _, _) => ("Heating", JobTone::Paused),
            (Some(_), _, _) => ("Printing", JobTone::Active),
        };
        let layers = self.toolpath.layers.len();
        frame.render_widget(
            JobProgress::new(self.name.as_str(), progress)
                .elapsed(elapsed)
                .eta(eta)
                .layer((layers > 0).then_some((current, layers)))
                .status(status, tone)
                .block(
                    Block::bordered()
                        .title(Span::styled(" Job ", theme.title()))
                        .border_style(theme.border(false)),
                )
                .theme(theme),
            job_area,
        );

        // Temperatures.
        frame.render_widget(
            TempChart::new(&self.temps)
                .window(Duration::from_secs(600))
                .block(
                    Block::bordered()
                        .title(Span::styled(" Temperatures ", theme.title()))
                        .border_style(theme.border(false)),
                )
                .theme(theme),
            chart_area,
        );
        let heaters_block = Block::bordered()
            .title(Span::styled(" Heaters ", theme.title()))
            .border_style(theme.border(false));
        let inner = heaters_block.inner(heaters_area);
        frame.render_widget(heaters_block, heaters_area);
        let [t0, bed] =
            Layout::vertical([Constraint::Length(1), Constraint::Length(1)]).areas(inner);
        frame.render_widget(
            HeaterGauge::new(
                HeaterKind::Hotend(0),
                self.hotend.current,
                Some(self.hotend.target),
            )
            .power(Some(self.hotend.power))
            .label_width(3)
            .theme(theme),
            t0,
        );
        frame.render_widget(
            HeaterGauge::new(HeaterKind::Bed, self.bed.current, Some(self.bed.target))
                .power(Some(self.bed.power))
                .label_width(3)
                .theme(theme),
            bed,
        );

        // Console.
        let mut title = String::from(" Console ");
        if !self.console_state.is_following() {
            title.push_str("(scrolled) ");
        }
        if self.show_auto {
            title.push_str("+auto ");
        }
        let search = (!self.search.is_empty()).then_some(self.search.as_str());
        let view = ConsoleView::new(&self.console)
            .show_auto(self.show_auto)
            .search(search)
            .theme(theme);
        if search.is_some() {
            title.push_str(&format!("[{} matches] ", view.match_count()));
        }
        frame.render_stateful_widget(
            view.block(
                Block::bordered()
                    .title(Span::styled(title, theme.title()))
                    .border_style(theme.border(false)),
            ),
            console_area,
            &mut self.console_state,
        );

        // Command or search line.
        let (input, title, placeholder) = match self.focus {
            Focus::Search => (&self.search_input, " Search ", "text to highlight"),
            _ => (
                &self.command,
                " Command ",
                "press : and type G-code (Tab completes)",
            ),
        };
        let focused = self.focus != Focus::View;
        let line = CommandLine::new(input)
            .placeholder(placeholder)
            .focused(focused)
            .theme(theme)
            .block(
                Block::bordered()
                    .title(Span::styled(title, theme.title()))
                    .border_style(theme.border(focused)),
            );
        if let Some(pos) = line.cursor_position(input_area) {
            frame.set_cursor_position(pos);
        }
        frame.render_widget(line, input_area);
        let popup = CompletionPopup::new(input).theme(theme);
        if let Some(popup_area) = popup.area(input_area, frame.area()) {
            frame.render_widget(Clear, popup_area);
            frame.render_widget(popup, popup_area);
        }
    }

    fn draw_stats(&mut self, frame: &mut Frame, area: Rect) {
        let theme = &self.theme;
        let panel = StatsPanel::from_toolpath(&self.toolpath).theme(theme);
        let max_scroll = panel
            .line_count()
            .saturating_sub(usize::from(area.height.saturating_sub(2)));
        self.stats_scroll = self.stats_scroll.min(max_scroll);
        let title = format!(" Statistics: {} ", self.name);
        frame.render_widget(
            panel.scroll(self.stats_scroll).block(
                Block::bordered()
                    .title(Span::styled(title, theme.title()))
                    .border_style(theme.border(false)),
            ),
            area,
        );
    }
}

